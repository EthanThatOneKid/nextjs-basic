// src/compiler.ts — QB64 compilation step

import * as fs from 'fs';
import * as path from 'path';
import * as os from 'os';
import { execSync } from 'child_process';
import { CompilerNotFoundError, CompileError } from './types';

// Path to the framework runtime.bas bundled with the package
const RUNTIME_BAS = path.join(__dirname, '..', 'src', 'runtime', 'runtime.bas');

function findQb64(): string {
  // Allow override via environment variable
  if (process.env.QB64_PATH) return process.env.QB64_PATH;

  // Try to locate qb64 on PATH
  try {
    const cmd = os.platform() === 'win32' ? 'where qb64' : 'which qb64';
    const result = execSync(cmd, { encoding: 'utf8' }).trim().split('\n')[0].trim();
    if (result) return result;
  } catch {
    // not on PATH
  }

  throw new CompilerNotFoundError();
}

export function compileRoute(basFile: string, outDir: string): string {
  const qb64 = findQb64();
  const routeName = path.basename(path.dirname(basFile));

  // Read framework runtime, generated glue, and user route
  const runtimeSrc = fs.readFileSync(RUNTIME_BAS, 'utf8');
  const userSrc = fs.readFileSync(basFile, 'utf8');

  // route.glue.bas is generated by the codegen step into the same directory
  const glueFile = path.join(path.dirname(basFile), 'route.glue.bas');
  const glueSrc = fs.existsSync(glueFile) ? fs.readFileSync(glueFile, 'utf8') : '';

  // Concatenation order:
  //   1. runtime.bas  — framework STDIO loop + envelope TYPEs + JSON helpers
  //   2. route.glue.bas — generated ParseXxx / WriteXxx SUBs for user TYPEs
  //   3. route.bas    — user handler functions
  const combined = runtimeSrc + '\n\n' + glueSrc + '\n\n' + userSrc;

  // Write to a temp file
  const tmpFile = path.join(os.tmpdir(), `nextjs-basic-${routeName}-${Date.now()}.bas`);
  fs.writeFileSync(tmpFile, combined, 'utf8');

  // Ensure output directory exists
  fs.mkdirSync(outDir, { recursive: true });

  const ext = os.platform() === 'win32' ? '.exe' : '';
  const outBin = path.join(outDir, routeName + ext);

  try {
    execSync(`"${qb64}" -c "${tmpFile}" -o "${outBin}"`, {
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'pipe'],
    });
  } catch (err: unknown) {
    const stderr = (err as { stderr?: string }).stderr ?? String(err);
    throw new CompileError(basFile, stderr);
  } finally {
    // Always clean up the temp file
    try { fs.unlinkSync(tmpFile); } catch { /* ignore */ }
  }

  return outBin;
}
